const mongoose = require('mongoose');

const notificationSchema = new mongoose.Schema(
  {
    user: {
      type: mongoose.Schema.Types.ObjectId,
      ref: 'User',
      required: true,
    },
    title: {
      type: String,
      required: true,
    },
    message: {
      type: String,
      required: true,
    },
    type: {
      type: String,
      enum: ['TASK_MATCH', 'APPLICATION_NEW', 'APPLICATION_ACCEPTED', 'APPLICATION_REJECTED', 'TASK_COMPLETED', 'TASK_CONFIRMED', 'MESSAGE', 'BADGE_UNLOCKED', 'SYSTEM'],
      default: 'SYSTEM',
    },
    link: {
      type: String,
      default: '',
    },
    isRead: {
      type: Boolean,
      default: false,
    },
  },
  { timestamps: true }
);

module.exports = mongoose.model('Notification', notificationSchema);
